SELECT 'PedidosDB' AS baseDatos, c.TABLE_NAME AS tabla, c.ORDINAL_POSITION AS posicion,
       c.COLUMN_NAME AS columna, c.DATA_TYPE AS tipo,
       c.CHARACTER_MAXIMUM_LENGTH AS largo, c.NUMERIC_PRECISION AS precision,
       c.NUMERIC_SCALE AS escala, c.IS_NULLABLE AS permiteNulo
FROM PedidosDB.INFORMATION_SCHEMA.COLUMNS AS c

UNION ALL

SELECT 'LogisticaDB', c.TABLE_NAME, c.ORDINAL_POSITION, c.COLUMN_NAME, c.DATA_TYPE,
       c.CHARACTER_MAXIMUM_LENGTH, c.NUMERIC_PRECISION, c.NUMERIC_SCALE, c.IS_NULLABLE
FROM LogisticaDB.INFORMATION_SCHEMA.COLUMNS AS c

UNION ALL

SELECT 'TrabajadorDB', c.TABLE_NAME, c.ORDINAL_POSITION, c.COLUMN_NAME, c.DATA_TYPE,
       c.CHARACTER_MAXIMUM_LENGTH, c.NUMERIC_PRECISION, c.NUMERIC_SCALE, c.IS_NULLABLE
FROM TrabajadorDB.INFORMATION_SCHEMA.COLUMNS AS c

UNION ALL

SELECT 'AutenticacionDB', c.TABLE_NAME, c.ORDINAL_POSITION, c.COLUMN_NAME, c.DATA_TYPE,
       c.CHARACTER_MAXIMUM_LENGTH, c.NUMERIC_PRECISION, c.NUMERIC_SCALE, c.IS_NULLABLE
FROM AutenticacionDB.INFORMATION_SCHEMA.COLUMNS AS c

ORDER BY baseDatos, tabla, posicion;
